"""
HEXOD master database loader (2026-10-18).

Single source for POIs, creatures, biomes, resources and codex categories:
data/hexod_db/hexod_db.json, generated by scripts/build_hexod_db.py from the
spreadsheets in data/hexod_db/sources/. Map POIs/territories are loaded into the
DB with `manage.py import_hexod_db`; creatures/biomes/resources are read from the
JSON at runtime (read-only reference data).
"""
import json
import os
import random
import re
from functools import lru_cache
from pathlib import Path

REPO_DB = Path(__file__).resolve().parents[4] / 'data' / 'hexod_db' / 'hexod_db.json'
# On the VPS the refreshed DB (Wikipedia pictures, verified candidates) lives outside the repo: HEXOD_DB_JSON in .env.prod
_env_db = os.environ.get('HEXOD_DB_JSON')
DB_PATH = Path(_env_db) if _env_db and Path(_env_db).exists() else REPO_DB

# Safari spawn odds by rarity and HEX reward on capture
SPAWN_WEIGHTS = {'common': 50, 'uncommon': 30, 'rare': 15, 'epic': 5}
CAPTURE_REWARD = {'common': 50, 'uncommon': 100, 'rare': 200, 'epic': 450, 'legendary': 1000}


# 4 rarities only (owner 2026-10-20): Silver 50 % · Gold 30 % · Emerald 15 % · Diamond 5 % (keys common / uncommon / rare
# / epic). Each family is ranked (best rarity first, then score) and cut by these shares; legendary / mythic fold into epic.
RARITY_QUOTAS = (('epic', 0.05), ('rare', 0.20), ('uncommon', 0.50), ('common', 1.0))
RANK = {'common': 0, 'uncommon': 1, 'rare': 2, 'epic': 3, 'legendary': 4, 'mythic': 5}


def apply_quotas(rows, family, score=lambda r: 0):
    """Rarity of every row from its rank inside its family (in place)."""
    groups = {}
    for i, r in enumerate(rows):
        groups.setdefault(family(r), []).append((i, r))
    for items in groups.values():
        ranked = sorted(items, key=lambda x: (-RANK.get(x[1].get('rarity') or 'common', 0), -(score(x[1]) or 0), x[0]))
        n, i = len(ranked), 0
        for rarity, cum in RARITY_QUOTAS:
            stop = n if rarity == 'common' else max(i, min(n, round(n * cum)))
            for _, r in ranked[i:stop]:
                r['rarity'] = rarity
            i = stop


TEXT_FIELDS = ('description', 'title', 'fun_fact_1', 'fun_fact_2', 'fun_fact_3', 'rare_fact')


def clean_text(s: str) -> str:
    """Absolute rule (owner 2026-10-19): never a double dash in game texts. Number ranges keep a plain hyphen
    (en dash 1000 – 2000 → 1000-2000); any other em dash / spaced en dash / "--" becomes a comma."""
    if not s or not re.search(r'--|—|–', s):
        return s
    s = re.sub(r'(\d)\s*–\s*(\d)', r'\1-\2', s)
    s = re.sub(r'\s*(?:--+|—|\s–\s|–)\s*', ', ', s)
    return re.sub(r',\s*([,.;:])', r'\1', s).strip(' ,')


@lru_cache(maxsize=1)
def load() -> dict:
    if not DB_PATH.exists():
        return {}
    with open(DB_PATH, encoding='utf-8') as f:
        db = json.load(f)
    for k in ('pois', 'creatures'):
        for row in db.get(k, []):
            for f in TEXT_FIELDS:
                if isinstance(row.get(f), str):
                    row[f] = clean_text(row[f])
    apply_quotas(db.get('creatures', []), family=lambda c: c.get('codex_category') or '')
    return db


# Safari = living nature only (owner 2026-10-19): fauna (animals, insects), flora (plants, fungi), micro-organisms, dinosaurs
SAFARI_FAMILIES = {'animal', 'insect', 'vegetal', 'mushroom', 'microOrganism', 'fossil'}


@lru_cache(maxsize=1)
def _creatures_by_rarity() -> dict:
    out: dict = {}
    for c in load().get('creatures', []):
        if not c.get('description') or c.get('needs_review'):   # wrong article / no text: not spawned
            continue
        if c.get('codex_category') not in SAFARI_FAMILIES:
            continue
        out.setdefault(c.get('rarity') or 'common', []).append(c)
    return out


def pick_creature(rng=random, with_places=False):
    """Rarity-weighted random creature, or None if the DB file is missing.
    with_places: only species whose real sightings / fossil sites are known (world safari)."""
    pools = _creatures_by_rarity()
    if with_places:
        pools = {r: [c for c in cs if c.get('places')] for r, cs in pools.items()}
    rarities = [r for r in SPAWN_WEIGHTS if pools.get(r)]
    if not rarities:
        return None
    rarity = rng.choices(rarities, weights=[SPAWN_WEIGHTS[r] for r in rarities])[0]
    return rng.choice(pools[rarity])


@lru_cache(maxsize=1)
def _creatures_by_uid() -> dict:
    return {c['uid']: c for c in load().get('creatures', [])}


def creature(uid: str):
    return _creatures_by_uid().get(uid)
