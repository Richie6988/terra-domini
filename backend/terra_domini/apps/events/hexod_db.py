"""
HEXOD master database loader (2026-10-18).

Single source for POIs, creatures, biomes, resources and codex categories:
data/hexod_db/hexod_db.json, generated by scripts/build_hexod_db.py from the
spreadsheets in data/hexod_db/sources/. Map POIs/territories are loaded into the
DB with `manage.py import_hexod_db`; creatures/biomes/resources are read from the
JSON at runtime (read-only reference data).
"""
import json
import os
import random
from functools import lru_cache
from pathlib import Path

REPO_DB = Path(__file__).resolve().parents[4] / 'data' / 'hexod_db' / 'hexod_db.json'
# On the VPS the refreshed DB (Wikipedia pictures, verified candidates) lives outside the repo: HEXOD_DB_JSON in .env.prod
_env_db = os.environ.get('HEXOD_DB_JSON')
DB_PATH = Path(_env_db) if _env_db and Path(_env_db).exists() else REPO_DB

# Safari spawn odds by rarity and HEX reward on capture
SPAWN_WEIGHTS = {'common': 55, 'uncommon': 25, 'rare': 13, 'epic': 6, 'legendary': 1}
CAPTURE_REWARD = {'common': 50, 'uncommon': 100, 'rare': 200, 'epic': 450, 'legendary': 1000}


@lru_cache(maxsize=1)
def load() -> dict:
    if not DB_PATH.exists():
        return {}
    with open(DB_PATH, encoding='utf-8') as f:
        return json.load(f)


@lru_cache(maxsize=1)
def _creatures_by_rarity() -> dict:
    out: dict = {}
    for c in load().get('creatures', []):
        if not c.get('description') or c.get('needs_review'):   # wrong article / no text: not spawned
            continue
        out.setdefault(c.get('rarity') or 'common', []).append(c)
    return out


def pick_creature(rng=random):
    """Rarity-weighted random creature, or None if the DB file is missing."""
    pools = _creatures_by_rarity()
    rarities = [r for r in SPAWN_WEIGHTS if pools.get(r)]
    if not rarities:
        return None
    rarity = rng.choices(rarities, weights=[SPAWN_WEIGHTS[r] for r in rarities])[0]
    return rng.choice(pools[rarity])


@lru_cache(maxsize=1)
def _creatures_by_uid() -> dict:
    return {c['uid']: c for c in load().get('creatures', [])}


def creature(uid: str):
    return _creatures_by_uid().get(uid)
